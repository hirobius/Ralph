#!/usr/bin/env bash
# How Ralph Decides doc generator tests: scripts/generate-how-ralph-decides.sh
# (docs/HOW-RALPH-DECIDES.md generated from kit/lib.sh decision tables).
set -uo pipefail
cd "$(dirname "$0")" || exit 1
# shellcheck source=tests/helpers.sh
. ./helpers.sh

GEN="$REPO_DIR/scripts/generate-how-ralph-decides.sh"

new_root() { # <name>
  CASE_NAME=$1
  R=$(mktemp -d "${TMPDIR:-/tmp}/ralph-decides-XXXXXX")
  mkdir -p "$R/kit" "$R/docs"
  cp -r "$REPO_DIR/kit/"* "$R/kit/"
}

run() { # <script> [args...]
  local script=$1
  shift
  RUN_CODE=0
  RUN_OUT=$(bash "$script" --root "$R" "$@" 2>&1) || RUN_CODE=$?
}

# ── 1. Generation & --check on missing / stale ─────────────────────────────
new_root fresh-gen
run "$GEN" --check
assert_eq 1 "$RUN_CODE" "--check fails when HOW-RALPH-DECIDES.md is missing"

run "$GEN"
assert_eq 0 "$RUN_CODE" "generation succeeds"
[ -f "$R/docs/HOW-RALPH-DECIDES.md" ] && _ok "docs/HOW-RALPH-DECIDES.md created" || _fail "docs/HOW-RALPH-DECIDES.md created"

OUT1=$(cat "$R/docs/HOW-RALPH-DECIDES.md")
run "$GEN" --check
assert_eq 0 "$RUN_CODE" "--check passes when file is up to date"

run "$GEN"
assert_eq 0 "$RUN_CODE" "regenerating succeeds"
OUT2=$(cat "$R/docs/HOW-RALPH-DECIDES.md")
assert_eq "$OUT1" "$OUT2" "generation is deterministic"

printf '\nHand edit.\n' >>"$R/docs/HOW-RALPH-DECIDES.md"
run "$GEN" --check
assert_eq 1 "$RUN_CODE" "--check fails when file is stale"
assert_contains "$RUN_OUT" "out of date" "names out of date on stale check"

# ── 2. All ralph_approver_reason codes appear (parsed from fixture) ────────
new_root codes-check
run "$GEN"
assert_eq 0 "$RUN_CODE" "generation succeeds"
OUT=$(cat "$R/docs/HOW-RALPH-DECIDES.md")

# Ensure marker is present at start
assert_contains "$OUT" "generated by scripts/generate-how-ralph-decides.sh from kit/lib.sh — do not hand-edit" "starts with generated do-not-hand-edit marker"

CODES=()
while IFS= read -r code; do
  [ -n "$code" ] && CODES+=("$code")
done < <(awk '
  /ralph_approver_reason\(\)/ { inside = 1; next }
  inside && /case / { in_case = 1; next }
  inside && in_case && /esac/ { inside = 0; in_case = 0 }
  inside && in_case {
    sub(/^[ \t]*/, "")
    if ($0 ~ /^[A-Za-z0-9_-]+\)/) {
      sub(/\).*/, "")
      print $0
    }
  }
' "$R/kit/lib.sh")

[ "${#CODES[@]}" -gt 0 ] && _ok "parsed codes from case block" || _fail "parsed codes from case block"

for code in "${CODES[@]}"; do
  assert_contains "$OUT" "$code" "output contains code $code"
done

# ── 3. Exact priority order & boundary sentence ────────────────────────────
assert_contains "$OUT" "1. \`ralph-approved\` — PR carries the \`ralph-approved\` label." "exact arm reason 1"
assert_contains "$OUT" "2. \`issue ralph-auto\` — Linked issue carries the \`ralph-auto\` label." "exact arm reason 2"
assert_contains "$OUT" "3. \`approver\` — \`RALPH_APPROVER=on\` and \`ralph_approver_decide\` evaluated to \`merge\`." "exact arm reason 3"
assert_contains "$OUT" "4. \`default posture\` — \`RALPH_DEFAULT_AUTO_MERGE\` posture is enabled (\`true\`)." "exact arm reason 4"

pos1=$(grep -n "1. \`ralph-approved\`" "$R/docs/HOW-RALPH-DECIDES.md" | cut -d: -f1)
pos2=$(grep -n "2. \`issue ralph-auto\`" "$R/docs/HOW-RALPH-DECIDES.md" | cut -d: -f1)
pos3=$(grep -n "3. \`approver\`" "$R/docs/HOW-RALPH-DECIDES.md" | cut -d: -f1)
pos4=$(grep -n "4. \`default posture\`" "$R/docs/HOW-RALPH-DECIDES.md" | cut -d: -f1)

[ "$pos1" -lt "$pos2" ] && [ "$pos2" -lt "$pos3" ] && [ "$pos3" -lt "$pos4" ] && _ok "arm reasons appear in exact order" || _fail "arm reasons appear in exact order"

assert_contains "$OUT" "**Supervised Path Boundary:** A supervised-path diff blocks arming under every reason (including explicit \`ralph-approved\` and \`issue ralph-auto\` labels)." "exact supervised path boundary statement"

# ── 4. Fixtures: extra code / missing code / unreferenced code ─────────────
new_root extra-code-fixture
sed -i '/10 otherwise/a #   11 extra-condition                             → escalate extra-code' "$R/kit/lib.sh"
sed -i '/policy-clear)/a \    extra-code) echo "Extra test reason sentence." ;;' "$R/kit/lib.sh"

run "$GEN"
assert_eq 0 "$RUN_CODE" "generation succeeds on fixture with extra row and code"
EXTRA_OUT=$(cat "$R/docs/HOW-RALPH-DECIDES.md")
assert_contains "$EXTRA_OUT" "extra-code" "output contains extra code"
assert_contains "$EXTRA_OUT" "Extra test reason sentence." "output contains extra reason sentence"

new_root missing-reason-fixture
sed -i '/policy-clear)/d' "$R/kit/lib.sh"
run "$GEN"
assert_eq 1 "$RUN_CODE" "deleting a reason line makes generator fail"
assert_contains "$RUN_OUT" "policy-clear" "error names code missing a reason sentence"

new_root unreferenced-reason-fixture
sed -i '/policy-clear)/a \    unreferenced-code) echo "Unreferenced." ;;' "$R/kit/lib.sh"
run "$GEN"
assert_eq 1 "$RUN_CODE" "adding unreferenced reason code makes generator fail"
assert_contains "$RUN_OUT" "unreferenced-code" "error names unreferenced reason code"

report
